"""
Whitespace se refiere a cualquier caracter que no se imprime, es decir, un espacio,
tabuladores (\t) y finales de linea (\n)

Los whitepaces se utilizan comunmente para organizar las salidadas de tal manera que sea mas amigable de leer o ver para los usuarios.
"""
print("Python")
print("\tPython")
print("\t\tPython")

programming_languages = "Lenguajes:\nPython\nC\n\tJavaScript"
print(programming_languages)
